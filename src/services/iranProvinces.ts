export const IRAN_PROVINCES: ProvinceCitiesGroup[] = RAW_IRAN_PROVINCES.map((prov) => ({
  province: prov.province,
  lat: prov.lat,
  lng: prov.lng,
  cities: prov.cities.map((c, idx) => {
    if (typeof c === 'string') {
      return {
        name: c,
        province: prov.province,
        lat: prov.lat + (idx % 5) * 0.04,
        lng: prov.lng + (idx % 4) * 0.04,
        defaultAddress: `${c}، بلوار اصلی، خیابان مرکزی`,
        neighborhoods: ['مرکز شهر', 'بلوار امام', 'شهرک فرهنگیان', 'خیابان انقلاب', 'میدان اصلی']
      };
    }
    return {
      name: c.name,
      province: prov.province,
      lat: c.lat ?? prov.lat,
      lng: c.lng ?? prov.lng,
      defaultAddress: `${c.name}، ${(c.neighborhoods && c.neighborhoods[0]) || 'مرکز شهر'}، پلاک ۱۰`,
      neighborhoods: c.neighborhoods || ['مرکز شهر', 'میدان اصلی', 'خیابان امام']
    };
  })
}));

export const ALL_IRAN_CITIES: TandisCityInfo[] = IRAN_PROVINCES.flatMap((p) => p.cities);

export function findNearestIranCity(lat: number, lng: number): TandisCityInfo {
  let best = ALL_IRAN_CITIES[0];
  let bestDist = Infinity;
  for (const city of ALL_IRAN_CITIES) {
    const dLat = city.lat - lat;
    const dLng = city.lng - lng;
    const dist = dLat * dLat + dLng * dLng;
    if (dist < bestDist) {
      bestDist = dist;
      best = city;
    }
  }
  return best;
}
